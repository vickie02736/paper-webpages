#!/usr/bin/env node
'use strict';
// Build the offline explainer subset and the evidence gap ledger from the catalogue.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'references/paper-catalog.json'), 'utf8'));
const entries = new Map(catalog.themes.flatMap(t => t.p).map(p => [p.u, p]));
const metadata = catalog.paperMetadata;
assert(metadata && typeof metadata === 'object', 'paperMetadata is required');
assert.deepEqual(Object.keys(metadata).sort(), [...entries.keys()].sort(), 'Metadata keys must match the unique paper sources');
const statuses = ['verified', 'unverified', 'notDisclosed', 'notApplicable'];
const validDate = value => {
  if (!/^\d{4}(?:-\d{2}){0,2}$/.test(value)) return false;
  const full = value.length === 4 ? value + '-01-01' : value.length === 7 ? value + '-01' : value;
  const date = new Date(full + 'T00:00:00Z');
  return Number.isFinite(+date) && date.toISOString().slice(0, 10) === full;
};
const bundle = {};
const missing = [];
const counts = {papers: entries.size, authors: 0, affiliations: 0, completeMappings: 0, published: 0, accepted: 0, preprint: 0, acceptanceNotDisclosed: 0};
const aliasesValid = item => !item.aliases || (Array.isArray(item.aliases) && item.aliases.every(a => typeof a === 'string' && a.trim()));
for (const [url, paper] of entries) {
  const m = metadata[url];
  assert(m, 'Missing metadata record: ' + url);
  assert(Array.isArray(m.authors) && Array.isArray(m.affiliations) && Array.isArray(m.sources), url + ': arrays');
  assert(validDate(m.checkedAt) && m.checkedAt.length === 10, url + ': checkedAt');
  const ids = new Set(m.affiliations.map(a => a.id));
  assert(ids.size === m.affiliations.length, url + ': duplicate affiliation id');
  for (const a of m.affiliations) assert(typeof a.id === 'string' && a.id && typeof a.name === 'string' && a.name.trim() && !/[<>@]|https?:\/\//.test(a.name) && aliasesValid(a), url + ': affiliation');
  for (const a of m.authors) {
    assert(typeof a.name === 'string' && a.name.trim() && Array.isArray(a.affiliations), url + ': author');
    assert(a.affiliations.every(id => ids.has(id)), url + ': unresolved affiliation for ' + a.name);
    assert(aliasesValid(a), url + ': author aliases');
  }
  for (const s of m.sources) assert(/^https:\/\//.test(s.url) && Array.isArray(s.fields) && s.locator, url + ': source');
  for (const field of ['authors', 'affiliations']) if (m[field].length) assert(m.sources.some(s => s.fields.includes(field)), url + ': missing evidence for ' + field);
  const gaps = [];
  if (m.authors.length) counts.authors++; else gaps.push('authors');
  if (m.affiliations.length) counts.affiliations++; else gaps.push('affiliations');
  if (m.authors.length && m.authors.every(a => a.affiliations.length)) counts.completeMappings++; else if (m.authors.length) gaps.push('author–affiliation mapping');
  for (const type of ['published', 'accepted', 'preprint']) {
    const d = m.dates[type];
    if (type === 'preprint' && !d) continue;
    assert(d && statuses.includes(d.status), url + ': date status ' + type);
    if (d.value) {
      assert(d.status === 'verified' && validDate(d.value) && m.sources.some(s => s.url === d.source), url + ': date/source ' + type);
      counts[type]++;
    } else {
      assert(d.status !== 'verified', url + ': verified date without a value');
      if (d.status === 'unverified') gaps.push(type);
      if (d.status === 'notDisclosed') {
        assert(d.source && m.sources.some(s => s.url === d.source), url + ': non-disclosure source');
        if (type === 'accepted') counts.acceptanceNotDisclosed++;
      }
    }
  }
  if (m.dates.accepted.value && m.dates.published.value) {
    const accepted = m.dates.accepted.value;
    const earliest = accepted.length === 4 ? accepted + '-01-01' : accepted.length === 7 ? accepted + '-01' : accepted;
    const latest = m.dates.published.value.length === 4 ? m.dates.published.value + '-12-31' : m.dates.published.value.length === 7 ? m.dates.published.value + '-31' : m.dates.published.value;
    assert(earliest <= latest || m.notes?.some(n => n.startsWith('Date chronology:')), url + ': acceptance after publication requires an evidence note');
  }
  if (gaps.length) missing.push({paper, gaps, m});
}
// A paper can have its explainer link in only one theme listing.
for (const theme of catalog.themes) for (const paper of theme.p) {
  if (!paper.p) continue;
  const match = /^\.\/papers\/([a-z0-9-]+)\/$/.exec(paper.p);
  assert(match, 'Invalid explainer path ' + paper.p);
  bundle[match[1]] = metadata[paper.u];
}
const output = '/* Generated by scripts/build-paper-metadata.cjs; edit references/paper-catalog.json. */\nwindow.AtlasPaperMetadata = ' + JSON.stringify(bundle).replace(/</g, '\\u003c') + ';\n';
const report = '# Paper metadata evidence and gaps\n\n' +
  'Generated from `paper-catalog.json`; checked dates and field-level source locators are stored with each record. This ledger concerns bibliographic metadata only.\n\n' +
  '核对结果：作者名单 ' + counts.authors + '/' + counts.papers + '；单位 ' + counts.affiliations + '/' + counts.papers + '；完整作者—单位对应 ' + counts.completeMappings + '/' + counts.papers + '。已核实发表日期 ' + counts.published + ' 篇、录用日期 ' + counts.accepted + ' 篇、首次预印本日期 ' + counts.preprint + ' 篇；另有 ' + counts.acceptanceNotDisclosed + ' 篇的已检查官方记录未披露录用日期。下列 ' + missing.length + ' 篇仍有至少一个未核实字段，不能视为全部信息已经核实。\n\n' +
  Object.entries(counts).map(([key, value]) => '- ' + key + ': ' + value).join('\n') + '\n\n' +
  'Dates use the precision published by the source. “Not disclosed” means the inspected official record does not disclose the date; “unverified” means the available evidence does not establish it. Preprint dates are separate from formal publication and acceptance. No conference notification date is substituted for a paper’s acceptance date. Author affiliation mappings are imported only when the source explicitly associates them.\n\n' +
  '## Records with unverified fields\n\n' + (missing.length ? missing.map(({paper, gaps, m}) => '- [' + paper.t.replace(/[\[\]]/g, '') + '](' + paper.u + '): ' + gaps.join(', ') + (m.notes?.length ? '. ' + m.notes.join(' ') : '')).join('\n') : 'None.') + '\n';
for (const [relative, content] of [['assets/paper-metadata.js', output], ['references/paper-metadata-audit.md', report]]) {
  const file = path.join(root, relative);
  if (process.argv.includes('--check')) assert(fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content, relative + ' is stale; run node scripts/build-paper-metadata.cjs');
  else fs.writeFileSync(file, content);
}
console.log(JSON.stringify({...counts, explainers: Object.keys(bundle).length, recordsWithGaps: missing.length}));
